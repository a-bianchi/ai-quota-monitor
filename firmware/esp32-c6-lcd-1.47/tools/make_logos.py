#!/usr/bin/env python3
"""Writes logos.cpp for both sketches from the panel's provider logos.

Run from anywhere, on macOS (it resizes with sips):

    python3 firmware/esp32-c6-lcd-1.47/tools/make_logos.py

Each logo becomes two RGB565 pictures, 30 and 14 px, with rounded corners
blended into the black background of the screen.
"""
import pathlib
import struct
import subprocess
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE.parents[2] / "server/internal/web/static/logos"
SKETCHES = [HERE.parent / "ai_quota_monitor_vertical", HERE.parent / "ai_quota_monitor_horizontal"]
# Order of enum Provider in model.h; None has no logo.
PROVIDERS = [None, "anthropic", "openai", "cursor", "openrouter", None]
SIZES = [(14, 3), (30, 7)]  # side and corner radius, small first


def pixels(path, side):
    """RGB rows of the picture resized to side x side."""
    with tempfile.TemporaryDirectory() as tmp:
        bmp = pathlib.Path(tmp) / "logo.bmp"
        subprocess.run(["sips", "-s", "format", "bmp", "-z", str(side), str(side), str(path), "--out", str(bmp)],
                       check=True, capture_output=True)
        data = bmp.read_bytes()
    offset, = struct.unpack_from("<I", data, 10)
    width, height = struct.unpack_from("<ii", data, 18)
    bpp, compression = struct.unpack_from("<HI", data, 28)
    if (width, abs(height)) != (side, side) or bpp not in (24, 32) or compression not in (0, 3):
        raise SystemExit(f"{path.name}: unexpected BMP {width}x{height}, {bpp} bpp, compression {compression}")
    step = bpp // 8
    stride = (width * step + 3) // 4 * 4
    rows = []
    for y in range(side):
        line = offset + (side - 1 - y if height > 0 else y) * stride
        rows.append([(data[line + x * step + 2], data[line + x * step + 1], data[line + x * step]) for x in range(side)])
    return rows


def coverage(x, y, side, radius):
    """Share of the pixel inside the rounded square, from 4 x 4 samples."""
    inside = 0
    for sy in range(4):
        for sx in range(4):
            px, py = x + (sx + 0.5) / 4, y + (sy + 0.5) / 4
            cx = min(max(px, radius), side - radius)
            cy = min(max(py, radius), side - radius)
            inside += (px - cx) ** 2 + (py - cy) ** 2 <= radius ** 2
    return inside / 16


def rgb565(rows, side, radius):
    out = []
    for y, row in enumerate(rows):
        for x, (r, g, b) in enumerate(row):
            k = coverage(x, y, side, radius)
            r, g, b = round(r * k), round(g * k), round(b * k)
            out.append((r >> 3) << 11 | (g >> 2) << 5 | b >> 3)
    return out


def main():
    text = [
        "// Generated by tools/make_logos.py from server/internal/web/static/logos.",
        "// Do not edit: change the pictures and run the script again.",
        '#include "logos.h"',
        "",
        "// Pixels in the byte order of lv_color_t.",
        "#if LV_COLOR_16_SWAP",
        "#define PX(v) (uint8_t)((v) >> 8), (uint8_t)((v) & 0xFF)",
        "#else",
        "#define PX(v) (uint8_t)((v) & 0xFF), (uint8_t)((v) >> 8)",
        "#endif",
        "",
    ]
    for name in filter(None, PROVIDERS):
        for side, radius in SIZES:
            values = rgb565(pixels(SOURCE / f"{name}.jpg", side), side, radius)
            text.append(f"static const uint8_t {name}_{side}[] = {{")
            for i in range(0, len(values), 10):
                text.append("  " + " ".join(f"PX(0x{v:04X})," for v in values[i:i + 10]))
            text.append("};")
            text.append("")
    text.append("// Indexed by Provider, then small and large.")
    text.append("static const uint8_t *const maps[][2] = {")
    for name in PROVIDERS:
        text.append("  { nullptr, nullptr }," if name is None else "  { %s }," % ", ".join(f"{name}_{side}" for side, _ in SIZES))
    text.append("};")
    text.append("")
    text.append("""static lv_img_dsc_t images[sizeof(maps) / sizeof(maps[0])][2];

const lv_img_dsc_t *logoFor(Provider provider, bool large) {
  if (provider >= sizeof(maps) / sizeof(maps[0]) || !maps[provider][large]) {
    return nullptr;
  }
  int side = large ? LOGO_LARGE : LOGO_SMALL;
  lv_img_dsc_t &image = images[provider][large];
  image.header.cf = LV_IMG_CF_TRUE_COLOR;
  image.header.w = side;
  image.header.h = side;
  image.data_size = side * side * 2;
  image.data = maps[provider][large];
  return &image;
}
""")
    for sketch in SKETCHES:
        (sketch / "logos.cpp").write_text("\n".join(text), encoding="utf-8")
        print("wrote", sketch / "logos.cpp")


if __name__ == "__main__":
    main()
